const agentReq = async (
  method: string,
  pathname: string,
  body?: unknown,
  timeoutMs = 30_000,
  token = AGENT_TOKEN
) => {
  try {
    return await httpRequest(
      `http://127.0.0.1:${AGENT_PORT}${pathname}`,
      {
        method,
        headers: {
          authorization: `Bearer ${token}`,
          ...(body === undefined ? {} : { 'content-type': 'application/json' }),
        },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }),
      },
      timeoutMs
    )
  } catch (error) {
    return { status: 0, text: errorMessage(error), json: undefined }
  }
}

