const scenarioCycles = async (): Promise<void> => {
  await report.group(
    '11',
    '20 sequential create/delete cycles: no leaked taps, nft rules, processes, run dirs or leases',
    async () => {
      for (let index = 1; index <= 20; index += 1) {
        const team = `cycle-${index}`
        const started = Date.now()
        const created = await provider.createInstance(createOptions(team))
        if (!isDetails(created)) {
          report.fail(
            `11.${index}`,
            `cycle ${index}: create/run/delete leaves no leak`,
            `create failed: ${short(created)}`
          )
          continue
        }
        await waitRunning(team)
        const id = await idFor(team)
        const record = agentRecord(id)
        let identity: { pid: number; tap: string; guestIp: string }
        try {
          identity = requireIdentity(record, id)
        } catch (error) {
          report.fail(
            `11.${index}`,
            `cycle ${index}: create/run/delete leaves no leak`,
            errorMessage(error)
          )
          continue
        }
        const served = await guestFlagMatches(identity.guestIp)
        // Calibrate the absence probes while the lease is definitely live.
        const live = inspectLease(shell, identity.tap, identity.guestIp)
        const calibrated = live.ok
        const deleted = await provider.deleteInstance(query(team))
        await waitStopped(team)
        const gone = await waitTeardown(
          id,
          identity.pid,
          identity.tap,
          identity.guestIp
        )
        const list = await agentList()
        const info = await agentInfo()
        const global = {
          processes: fcProcessesForRun().length,
          taps: tapsInNetns().length,
          runDirs: runDirEntries().length,
          stateFiles: stateFileCount(),
          rows: controllerRows().length,
          agentInstances: list.length,
          usageInstances: info.usage.instances,
          nftLeases: nftHasLeaseRules(nftText()),
        }
        const clean =
          served &&
          calibrated &&
          isDetails(deleted) &&
          deleted.status === 'stopped' &&
          gone.all &&
          Object.entries(global).every(([key, value]) =>
            key === 'nftLeases' ? value === false : value === 0
          )
        report.check(
          `11.${index}`,
          `cycle ${index}: create/run/delete leaves no leak`,
          clean,
          `served=${served} calibrated=${calibrated} gone=${JSON.stringify(
            gone
          )} global=${JSON.stringify(global)} ${Date.now() - started}ms`
        )
      }
    }
  )
}

const scenarioAmbiguousCreate = async (): Promise<void> => {
  await report.group(
    '7',
    'ambiguous create: swallowed response, fence DELETE, tombstone, later create',
    async () => {
      await stopController()
      await startController(CONTROLLER_PROXY_CONFIG, 'proxy')
      await waitForTrue(
        'host healthy through the proxy',
        async () => (await hostHealth()) === 'healthy',
        30_000,
        200
      )

      // --- 7a: the create response is swallowed but the VM exists ---------
      proxy.arm('drop-response')
      const teamA = 'amb-live'
      const created = await provider.createInstance(createOptions(teamA))
      const rowA = rowsForTeam(teamA)[0]
      report.check(
        '7.1',
        'the provider reports the ambiguous create as starting (no transport error leaks to the player)',
        isDetails(created) && created.status === 'starting',
        short(created)
      )
      report.check(
        '7.2',
        'the controller row stays creating after the swallowed response',
        rowA?.state === 'creating',
        `state=${rowA?.state}`
      )
      if (rowA === undefined) throw new Error('ambiguous row missing')
      const idA = rowA.id
      report.check(
        '7.3',
        'the VM was really created despite the swallowed response',
        proxy.forwardedCreateIds.includes(idA) &&
          (await agentGet(idA)) !== null,
        `forwarded=${proxy.forwardedCreateIds.join(',')}`
      )
      await waitFor(
        'ambiguous VM running',
        () => agentGet(idA),
        value => value?.state === 'running',
        40_000,
        200
      )
      // Restarting triggers exactly one reconciler tick (the proxy controller
      // runs with an effectively manual reconcile interval), so adoption is
      // deterministic.
      await restartController(CONTROLLER_PROXY_CONFIG, 'proxy-adopt')
      const adopted = await waitFor(
        'ambiguous row adopted',
        () => rowsForTeam(teamA)[0],
        value => value?.state === 'running',
        40_000,
        200
      )
      const identityA = requireIdentity(agentRecord(idA), idA)
      report.check(
        '7.4',
        'the reconciler adopts the live VM after an ambiguous create (same id, one VM)',
        adopted?.id === idA &&
          (await agentList()).length === 1 &&
          fcProcessesForRun().length === 1,
        `row=${adopted?.state}`
      )
      report.check(
        '7.5',
        'the adopted guest still serves the flag',
        await guestFlagMatches(identityA.guestIp)
      )
      await provider.deleteInstance(query(teamA))
      await waitStopped(teamA)

      // --- 7b: the create never reaches the agent; the fence must win -----
      proxy.arm('hold-request')
      const teamB = 'amb-fence'
      const createdB = await provider.createInstance(createOptions(teamB))
      const rowB = rowsForTeam(teamB)[0]
      report.check(
        '7.6',
        'the row stays creating when the create never reached the agent',
        isDetails(createdB) && rowB?.state === 'creating',
        `create=${short(createdB)} state=${rowB?.state}`
      )
      if (rowB === undefined) throw new Error('fenced row missing')
      const idB = rowB.id
      const captured = proxy.captured.find(entry => entry.id === idB)
      report.check(
        '7.7',
        'the proxy captured the create request and the agent has no record of it',
        captured !== undefined && (await agentGet(idB)) === null,
        `captured=${captured !== undefined}`
      )
      await sleep(6_000) // > createFenceSeconds (4s)
      await restartController(CONTROLLER_PROXY_CONFIG, 'proxy-fence')
      await waitForTrue(
        'fenced row removed',
        () => rowsForTeam(teamB).length === 0,
        40_000,
        200
      )
      report.check(
        '7.8',
        'the fence DELETE removed the controller row',
        rowsForTeam(teamB).length === 0
      )
      report.check(
        '7.9',
        'the agent wrote a durable tombstone for the fenced id',
        existsSync(path.join(AGENT_STATE, 'tombstones', `${idB}.json`)),
        idB
      )
      report.check(
        '7.10',
        'no VM, run dir or state record was leaked for the fenced id',
        (await agentGet(idB)) === null &&
          !existsSync(path.join(AGENT_RUN, idB)) &&
          !existsSync(recordPath(idB))
      )
      if (captured === undefined) throw new Error('captured create missing')
      const replay = await replayCaptured(captured)
      report.check(
        '7.11',
        'a delayed PUT of the fenced create is rejected by the tombstone (409 conflict)',
        replay.status === 409 &&
          (replay.json as { code?: string } | undefined)?.code === 'conflict',
        `HTTP ${replay.status} ${short(replay.json)}`
      )
      report.check(
        '7.12',
        'the delayed PUT created no VM',
        (await agentGet(idB)) === null && fcProcessesForRun().length === 0
      )
      const later = await provider.createInstance(createOptions(teamB))
      await waitRunning(teamB)
      const laterId = await idFor(teamB)
      report.check(
        '7.13',
        'a later create for the same team works and gets a fresh id',
        isDetails(later) &&
          laterId !== idB &&
          (await agentGet(laterId)) !== null,
        `${idB} -> ${laterId}`
      )
      await provider.deleteInstance(query(teamB))
      await waitStopped(teamB)
      await stopController()
    }
  )
}

