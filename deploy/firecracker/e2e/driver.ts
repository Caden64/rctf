#!/usr/bin/env bun
/**
 * Unprivileged end-to-end harness:
 *
 *   rCTF provider (real code) --HTTP--> controller process (real HTTP + bun:sqlite)
 *     --HTTP (optionally through the fault proxy)--> agent process (real VmDriver,
 *     real NetworkManager, real nft/taps) --> real Firecracker microVM under KVM.
 *
 * Everything runs inside `unshare -Urn` (see run.sh), exactly like the smoke
 * test, so the taps and nftables rules are real but private to the namespace.
 *
 * The driver starts/stops the controller and agent processes itself so it can
 * kill them (SIGKILL) and restart them, and it observes the controller SQLite
 * and the agent state directory read-only for its assertions.
 */
