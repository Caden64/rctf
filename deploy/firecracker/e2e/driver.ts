let agentProcess: ManagedProcess | undefined
let controllerProcess: ManagedProcess | undefined
let agentStarts = 0
let controllerStarts = 0

const startAgent = async (): Promise<void> => {
  agentStarts += 1
  agentProcess = spawnManaged({
    name: 'agent',
    argv: [BUN, AGENT_SCRIPT, AGENT_CONFIG],
    cwd: REPO,
    env: { ...childEnv(), FIRECRACKER_AGENT_TOKEN: AGENT_TOKEN },
    logPath: path.join(LOGS, `agent-${agentStarts}.log`),
  })
  recordPid(`agent-${agentStarts}`, agentProcess.pid)
  try {
    await waitForTrue(
      'agent recovered and accepting',
      async () => {
        const result = await agentReq('GET', '/v1/info', undefined, 3_000)
        if (result.status !== 200) return false
        const info = result.json as {
          accepting?: boolean
          checks?: Record<string, boolean>
        }
        return info.accepting === true && info.checks?.recovered === true
      },
      40_000,
      200
    )
  } catch (error) {
    throw new Error(
      `${errorMessage(error)}\n--- agent log ---\n${tailFile(
        agentProcess.logPath,
        40
      )}`
    )
  }
}

const stopAgent = async (signal: NodeJS.Signals = 'SIGTERM'): Promise<void> => {
  const process = agentProcess
  agentProcess = undefined
  await terminate(process, { signal, timeoutMs: 10_000 })
}

const startController = async (
  configPath: string,
  label: string
): Promise<void> => {
  controllerStarts += 1
  controllerProcess = spawnManaged({
    name: `controller-${label}`,
    argv: [BUN, CONTROLLER_SCRIPT, configPath],
    cwd: REPO,
    env: {
      ...childEnv(),
      FIRECRACKER_CONTROLLER_AUTH_TOKEN: API_TOKEN,
      FIRECRACKER_CONTROLLER_ADMIN_TOKEN: ADMIN_TOKEN,
      FIRECRACKER_TEAM_KEY_SECRET: TEAM_KEY_SECRET,
      FIRECRACKER_HOST_TOKEN_FC1: AGENT_TOKEN,
    },
    logPath: path.join(LOGS, `controller-${label}-${controllerStarts}.log`),
  })
  recordPid(`controller-${controllerStarts}`, controllerProcess.pid)
  try {
    await waitForTrue(
      'controller /healthz',
      async () => {
        try {
          const result = await httpRequest(
            `http://127.0.0.1:${CONTROLLER_PORT}/healthz`,
            {},
            2_000
          )
          return result.status === 200
        } catch {
          return false
        }
      },
      40_000,
      100
    )
  } catch (error) {
    throw new Error(
      `${errorMessage(error)}\n--- controller log ---\n${tailFile(
        controllerProcess.logPath,
        60
      )}`
    )
  }
}

const stopController = async (
  signal: NodeJS.Signals = 'SIGTERM'
): Promise<void> => {
  const process = controllerProcess
  controllerProcess = undefined
  await terminate(process, { signal, timeoutMs: 10_000 })
  await sleep(300)
}

const restartController = async (
  configPath: string,
  label: string
): Promise<void> => {
  await stopController()
  await startController(configPath, label)
}

