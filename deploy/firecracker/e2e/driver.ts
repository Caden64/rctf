interface AgentInstance {
  id: string
  state: string
  message?: string
  createdAtMs: number
  expiresAtMs: number
  endpoints: Array<{ kind: string; host: string; port: number }>
  specHash: string
}

const agentList = async (): Promise<AgentInstance[]> => {
  const result = await agentReq('GET', '/v1/instances')
  if (result.status !== 200) {
    throw new Error(
      `agent list -> ${result.status}: ${short(result.text)} (agent must be up for this assertion)`
    )
  }
  if (!Array.isArray(result.json)) {
    throw new Error(`agent list returned a non-array: ${short(result.json)}`)
  }
  return result.json
}

const agentGet = async (id: string): Promise<AgentInstance | null> => {
  const result = await agentReq('GET', `/v1/instances/${id}`)
  if (result.status === 404) return null
  if (result.status !== 200) {
    throw new Error(
      `agent GET ${id} -> ${result.status}: ${short(result.text)}`
    )
  }
  return result.json as AgentInstance
}

